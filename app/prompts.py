def build_user_prompt(chapter_title: str, ordinal: int, text: str, context: str = "") -> str:
    """把章节元信息和原文包在清晰边界中。"""

    context_block = context.strip() or "当前没有已确认的前文记忆。"
    return f"""片段序号：{ordinal}
原文章节：{chapter_title}

<ESTABLISHED_CONTEXT>
{context_block}
</ESTABLISHED_CONTEXT>

<NOVEL_TEXT>
{text}
</NOVEL_TEXT>

请先理解这一段在本章和前文中的位置，再抽取值得长期保留的事实。上下文只用于规范名称和识别前后联系；每个 evidence_quote 仍须从 NOVEL_TEXT 逐字复制。描述必须交代具体人物、动作、条件和结果，避免用“推动剧情”“参与主线”“获得线索”等空泛句子代替内容。已经存在的实体沿用规范名，新称呼写入 aliases；原文没有明确支持的地理方位、时间、身份、因果或世界规则一律留空或省略。"""
